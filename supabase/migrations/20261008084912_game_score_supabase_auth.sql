-- Sprint 6. Dit bestand is aangemaakt met Supabase CLI migration new.
-- Prefix game_ voorkomt verwarring met tabellen van andere applicaties.

create table public.game_players (
    id bigint generated by default as identity primary key,
    username varchar(50) not null check (char_length(btrim(username)) between 1 and 50),
    username_key varchar(50) not null unique,
    owner_id uuid default auth.uid() references auth.users(id) on delete set null
);

create index game_players_owner_id_idx on public.game_players(owner_id);

create table public.game_scores (
    id bigint generated by default as identity primary key,
    player_id bigint not null references public.game_players(id) on delete cascade,
    points bigint not null check (points > 0)
);

create index game_scores_player_id_idx on public.game_scores(player_id);

-- Ook een directe Data API-request mag geen afwijkende username_key kiezen.
create function public.game_normalize_username()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
    new.username := pg_catalog.btrim(new.username);
    new.username_key := pg_catalog.lower(new.username);
    return new;
end;
$$;

revoke execute on function public.game_normalize_username() from public, anon, authenticated;

create trigger game_players_normalize_username
before insert or update of username on public.game_players
for each row execute function public.game_normalize_username();

alter table public.game_players enable row level security;
alter table public.game_scores enable row level security;

create policy game_players_public_read
on public.game_players for select to anon, authenticated
using (true);

create policy game_players_owner_insert
on public.game_players for insert to authenticated
with check (
    (select auth.uid()) = owner_id
    and not coalesce(((select auth.jwt()) ->> 'is_anonymous')::boolean, false)
);

create policy game_players_owner_update
on public.game_players for update to authenticated
using (
    (select auth.uid()) = owner_id
    and not coalesce(((select auth.jwt()) ->> 'is_anonymous')::boolean, false)
)
with check (
    (select auth.uid()) = owner_id
    and not coalesce(((select auth.jwt()) ->> 'is_anonymous')::boolean, false)
);

create policy game_players_owner_delete
on public.game_players for delete to authenticated
using (
    (select auth.uid()) = owner_id
    and not coalesce(((select auth.jwt()) ->> 'is_anonymous')::boolean, false)
);

create policy game_scores_public_read
on public.game_scores for select to anon, authenticated
using (true);

create policy game_scores_owner_insert
on public.game_scores for insert to authenticated
with check (
    not coalesce(((select auth.jwt()) ->> 'is_anonymous')::boolean, false)
    and exists (
        select 1 from public.game_players p
        where p.id = player_id and p.owner_id = (select auth.uid())
    )
);

-- De view volgt de RLS-policies van de onderliggende tabellen.
create view public.game_player_totals with (security_invoker = true) as
select p.id, p.username, coalesce(sum(s.points), 0)::bigint as score
from public.game_players p
left join public.game_scores s on s.player_id = p.id
group by p.id;

-- Beperk ook kolommen: clients mogen geen IDs of eigenaars achteraf wijzigen.
revoke all on public.game_players, public.game_scores, public.game_player_totals
from anon, authenticated;

grant select (id, username) on public.game_players to anon;
grant select on public.game_players to authenticated;
grant insert (username, owner_id), update (username), delete
on public.game_players to authenticated;

grant select on public.game_scores to anon, authenticated;
grant insert (player_id, points) on public.game_scores to authenticated;
grant select on public.game_player_totals to anon, authenticated;
grant usage on sequence public.game_players_id_seq, public.game_scores_id_seq to authenticated;
